// Eastbrook Vale v2 import: the repeatable bridge from the Unreal design exports to
// the server's Eastbrook data. Re-run it whenever the world crew re-exports:
//
//   npx tsx scripts/eastbrook_v2/import_eastbrook_v2.ts --src <WorldDesign/EastbrookVale>
//   npx tsx scripts/eastbrook_v2/import_eastbrook_v2.ts --src <dir> --check   (exit 1 if stale)
//   ... --commit <sha>   (the source commit, when --src is a snapshot, not a checkout)
//
// Then stand the content on the new ground and re-pin the live-world baseline:
//   npx tsx scripts/eastbrook_v2/resite_eastbrook_v2.ts   (repeat until --check passes)
//   node scripts/eastbrook_v2/rebase_live_world.mjs       (after every resite)
//
// --src defaults to $EASTBROOK_V2_SRC. Writes src/sim/eastbrook_v2/field.generated.ts,
// src/sim/eastbrook_v2/layout.generated.ts and data/eastbrook_v2/manifest.json (the
// source commit, a sha256 per input and the conversion counts). Settings live in
// data/eastbrook_v2/import_config.json; the conversion itself is import_core.ts.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  convertColliders,
  convertField,
  convertNodes,
  convertPoints,
  convertRestAreas,
  convertRoads,
  type ImportConfig,
  int16ToBase64,
} from './import_core';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const INPUTS = ['heightfield.json', 'colliders.json', 'points.json', 'nodes.json', 'roads.json'];

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const src = arg('--src') ?? process.env.EASTBROOK_V2_SRC;
const check = process.argv.includes('--check');
if (!src) {
  console.error('usage: import_eastbrook_v2.ts --src <WorldDesign/EastbrookVale> [--check]');
  process.exit(2);
}
for (const f of INPUTS) {
  if (!existsSync(join(src, f))) {
    console.error(`missing export ${join(src, f)}`);
    process.exit(2);
  }
}

const cfg = JSON.parse(
  readFileSync(join(ROOT, 'data', 'eastbrook_v2', 'import_config.json'), 'utf8'),
) as ImportConfig;
const raw = Object.fromEntries(INPUTS.map((f) => [f, readFileSync(join(src, f), 'utf8')]));
const sha = Object.fromEntries(
  INPUTS.map((f) => [f, createHash('sha256').update(raw[f]).digest('hex')]),
);
// --commit names the source commit when --src is a snapshot (git show of the
// world crew's branch) rather than a checkout.
let commit = arg('--commit') ?? 'unknown';
if (commit === 'unknown') {
  try {
    commit = execFileSync('git', ['-C', src, 'log', '-1', '--format=%H', '--', '.'], {
      encoding: 'utf8',
    }).trim();
  } catch {
    // not a git checkout: the hashes still identify the inputs
  }
}

const field = convertField(JSON.parse(raw['heightfield.json']), cfg);
const designNodes = JSON.parse(raw['nodes.json']).nodes;
const nodeIds = new Set<string>(
  designNodes.filter((n: { kind: string }) => n.kind !== 'tree').map((n: { id: string }) => n.id),
);
const colliders = convertColliders(
  JSON.parse(raw['colliders.json']).colliders,
  field,
  cfg,
  nodeIds,
);
const restAreas = convertRestAreas(JSON.parse(raw['colliders.json']).colliders, cfg);
const points = convertPoints(JSON.parse(raw['points.json']).points, cfg);
const nodes = convertNodes(designNodes, cfg);
const roads = convertRoads(JSON.parse(raw['roads.json']).roads, cfg);

const HEADER = [
  '// GENERATED by scripts/eastbrook_v2/import_eastbrook_v2.ts from the Unreal Eastbrook Vale',
  '// design exports. Do not edit by hand: re-run the import (data/eastbrook_v2/manifest.json',
  '// names the source commit and input hashes).',
];

const b64 = int16ToBase64(field.heights);
const chunks: string[] = [];
for (let i = 0; i < b64.length; i += 96) chunks.push(b64.slice(i, i + 96));
const fieldTs = [
  ...HEADER,
  '// Server-frame ground heights in centimetres, int16 little-endian, z rows of x.',
  '',
  'export const EBV2_FIELD_GRID = {',
  `  x0: ${field.x0},`,
  `  z0: ${field.z0},`,
  `  nx: ${field.nx},`,
  `  nz: ${field.nz},`,
  `  yOffset: ${cfg.yOffset},`,
  `  edgeBand: ${cfg.edgeBand},`,
  '} as const;',
  '',
  'export const EBV2_CORRIDORS = [',
  ...cfg.corridors.map(
    (c) =>
      `  { id: '${c.id}', ax: ${c.ax}, az: ${c.az}, bx: ${c.bx}, bz: ${c.bz}, halfWidth: ${c.halfWidth}, blend: ${c.blend} },`,
  ),
  '] as const;',
  '',
  'export const EBV2_HEIGHTS_B64 = [',
  ...chunks.map((c) => `  '${c}',`),
  "].join('');",
  '',
].join('\n');

const json = (v: unknown) => JSON.stringify(v);
const layoutTs = [
  ...HEADER,
  '// Everything the server reads from the design besides the ground: oriented boxes as',
  '// [x, z, halfWidth, halfDepth, rot, top] (rot is the three.js yaw, top server-frame),',
  '// points and nodes by their design id, the wild trees and the roads, all clipped to',
  '// the eastbrook_vale slot.',
  '',
  'export type Ebv2ColliderRow = readonly [number, number, number, number, number, number];',
  'export interface Ebv2Point {',
  '  readonly id: string;',
  '  readonly kind: string;',
  '  readonly name: string;',
  '  readonly x: number;',
  '  readonly y: number;',
  '  readonly z: number;',
  '  readonly radius?: number;',
  '  readonly width?: number;',
  '}',
  'export interface Ebv2Node {',
  '  readonly id: string;',
  "  readonly kind: 'ore' | 'herb' | 'berry' | 'fishing';",
  '  readonly x: number;',
  '  readonly y: number;',
  '  readonly z: number;',
  '}',
  'export interface Ebv2Road {',
  '  readonly id: string;',
  '  readonly width: number;',
  '  readonly points: readonly (readonly [number, number])[];',
  '}',
  '',
  'export const EBV2_COLLIDERS: readonly Ebv2ColliderRow[] = [',
  ...colliders.rows.map((r) => `  ${json(r)},`),
  '];',
  '',
  'export const EBV2_COLLIDER_IDS: readonly string[] = [',
  ...colliders.ids.map((id) => `  '${id}',`),
  '];',
  '',
  'export const EBV2_POINTS: readonly Ebv2Point[] = [',
  ...points.map((p) => `  ${json(p)},`),
  '];',
  '',
  'export const EBV2_NODES: readonly Ebv2Node[] = [',
  ...nodes.nodes.map((n) => `  ${json(n)},`),
  '];',
  '',
  '/** Wild trees, [x, z] in export order (EBV2_TREE_IDS holds their design ids). */',
  'export const EBV2_TREES: readonly (readonly [number, number])[] = [',
  ...nodes.trees.map((t) => `  ${json(t)},`),
  '];',
  '',
  'export const EBV2_TREE_IDS: readonly string[] = [',
  ...nodes.treeIds.map((id) => `  '${id}',`),
  '];',
  '',
  'export const EBV2_ROADS: readonly Ebv2Road[] = [',
  ...roads.map((r) => `  ${json(r)},`),
  '];',
  '',
  "/** Where a body rests (rested XP): each rest building's footprint, as",
  " *  [x, z, halfWidth, halfDepth, rot] in the collider rows' convention. */",
  'export const EBV2_REST_AREAS: readonly (readonly [number, number, number, number, number])[] = [',
  ...restAreas.map((r) => `  ${json(r)},`),
  '];',
  '',
].join('\n');

const manifest = `${JSON.stringify(
  {
    note: 'Written by scripts/eastbrook_v2/import_eastbrook_v2.ts. Do not edit by hand.',
    source: { commit, files: sha },
    counts: {
      fieldCells: field.nx * field.nz,
      waterCells: field.waterCells,
      meanWaterSurface: field.meanWaterSurface,
      colliders: colliders.rows.length,
      collidersSkipped: colliders.skipped,
      points: points.length,
      nodes: Object.fromEntries(
        ['ore', 'herb', 'berry', 'fishing'].map((k) => [
          k,
          nodes.nodes.filter((n) => n.kind === k).length,
        ]),
      ),
      trees: nodes.trees.length,
      nodesOutsideSlot: nodes.outside,
      roads: roads.length,
    },
  },
  null,
  2,
)}\n`;

const outputs: [string, string][] = [
  [join(ROOT, 'src', 'sim', 'eastbrook_v2', 'field.generated.ts'), fieldTs],
  [join(ROOT, 'src', 'sim', 'eastbrook_v2', 'layout.generated.ts'), layoutTs],
  [join(ROOT, 'data', 'eastbrook_v2', 'manifest.json'), manifest],
];

if (check) {
  const stale = outputs.filter(([p, body]) => !existsSync(p) || readFileSync(p, 'utf8') !== body);
  for (const [p] of stale) console.error(`stale: ${p}`);
  process.exit(stale.length ? 1 : 0);
}
for (const [p, body] of outputs) writeFileSync(p, body);
console.log(manifest);
