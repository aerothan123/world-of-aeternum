// take from the shipped clip it replaces, and `loop: true` asks for a seamless loop.

const DRY = 'Close-mic and completely dry: no reverb, no music, no ambience.';
const APART = 'with a clear silent pause between each';

const withDry = (c) => {
  const p = c.prompt.replace('${APART}', APART);
  const shape = c.loop
    ? 'Continuous and even, a seamless loop. '
    : c.single
      ? 'Single sound. '
      : '';
  return { ...c, prompt: `${p}${p.endsWith('.') ? '' : '.'} ${shape}${DRY}` };
};

